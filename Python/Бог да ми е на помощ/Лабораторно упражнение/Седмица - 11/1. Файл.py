"""
Създаваме файл и го отваряме в режим на запис. Потребителят въвежда броя на редовете - n и ги записва във файла. Файлът се затваря и се отваря в режим на четене,
чете се съдържанието ред по ред и се принтира.
"""
file = open("Файл.txt", "w")
lines = int(input("Брой редове: "))
for line in range(lines):
    file.write(f"{input("Въведи текст: ")} ")
file.close()

file = open("Файл.txt", "r")
print(f"Резултат: {file.read()}")
file.close()
